"""Builds app/night.css: every `@media (prefers-color-scheme: dark)` block of app/styles.css, re-scoped to
`html[data-style=night]` so the 夜光 interface style is dark even when the phone is in light mode.
Run after changing any dark-mode rule:  python3 scripts/build-night-css.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
css = (root / 'app/styles.css').read_text()
P = 'html[data-style=night]'

def block_end(s, i):
    """s[i] == '{'; return index just past the matching '}'."""
    depth = 0
    for j in range(i, len(s)):
        if s[j] == '{': depth += 1
        elif s[j] == '}':
            depth -= 1
            if depth == 0: return j + 1
    raise ValueError('unbalanced braces')

def split_selectors(sel):
    out, depth, cur = [], 0, ''
    for ch in sel:
        if ch in '([': depth += 1
        elif ch in ')]': depth -= 1
        if ch == ',' and depth == 0: out.append(cur); cur = ''
        else: cur += ch
    out.append(cur)
    return [x.strip() for x in out if x.strip()]

def scope(sel):
    if sel.startswith(':root'): return P + sel[5:]
    if sel.startswith('html'): return P + sel[4:]
    return f'{P} {sel}'

def rescope(body):
    """Prefix every rule in a block body; nested at-rules keep their condition."""
    out, i = [], 0
    while i < len(body):
        j = body.find('{', i)
        if j < 0: break
        head = body[i:j].strip()
        end = block_end(body, j)
        inner = body[j + 1:end - 1]
        if head.startswith('@keyframes'): out.append(f'{head}{{{inner}}}')
        elif head.startswith('@'): out.append(f'{head}{{{rescope(inner)}}}')
        elif head: out.append(','.join(scope(x) for x in split_selectors(head)) + '{' + inner + '}')
        i = end
    return ''.join(out)

parts = []
for m in re.finditer(r'@media\s*\(\s*prefers-color-scheme\s*:\s*dark\s*\)\s*\{', css):
    start = m.end() - 1
    parts.append(rescope(css[start + 1:block_end(css, start) - 1]))
out = '/* Generated by scripts/build-night-css.py from the dark-mode rules in styles.css. Do not edit. */\n' + f'{P}{{color-scheme:dark}}\n' + '\n'.join(parts) + '\n'
(root / 'app/night.css').write_text(out)
print(f'{len(parts)} dark blocks -> app/night.css ({len(out)} bytes)')

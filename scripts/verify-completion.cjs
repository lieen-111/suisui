const { chromium, review, url, launchOptions } = require('./test-environment.cjs');
const assert = require('node:assert/strict');
const path = require('node:path');
let browser;
(async () => {
  browser = await chromium.launch(launchOptions);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(url, { waitUntil: 'networkidle' });
  const list = page.locator('#activity-list');
  assert(await list.evaluate(el => el.scrollHeight > el.clientHeight));
  const headingBefore = await page.locator('.activity-heading').boundingBox();
  const footerBefore = await page.locator('#see-all').boundingBox();
  await list.hover();
  await page.mouse.wheel(0, 120);
  await page.waitForTimeout(150);
  const scrolled = await list.evaluate(el => el.scrollTop);
  assert(scrolled > 0, 'Mouse wheel scrolls inside the task box');
  assert.deepEqual(await page.locator('.activity-heading').boundingBox(), headingBefore);
  assert.deepEqual(await page.locator('#see-all').boundingBox(), footerBefore);
  const target = page.locator('.lock-task[data-id=seed-5]');
  await target.click();
  const scrollAtClick = await list.evaluate(el => el.scrollTop);
  await page.waitForTimeout(630);
  assert.equal(await target.getAttribute('aria-pressed'), 'true');
  assert.equal(await target.locator('s').count(), 1);
  assert.equal(await target.getAttribute('data-action'), 'restore');
  assert.equal(await page.locator('.lock-task').last().getAttribute('data-id'), 'seed-5', 'Completed item moves to the end');
  assert(Math.abs(await list.evaluate(el => el.scrollTop) - scrollAtClick) <= 1, 'Completing retains scroll position');
  assert.equal(await page.locator('#completed-section').evaluate(el => el.open), true);
  assert(await target.evaluate(el => el.classList.contains('completion-arrival')), 'Strike animation is running');
  await page.waitForTimeout(500);
  assert.equal(await target.evaluate(el => Number(getComputedStyle(el).opacity)), .5);
  assert((await target.locator('s').evaluate(el => getComputedStyle(el).textDecorationLine)).includes('line-through'));
  await page.screenshot({ path: path.resolve(__dirname, '../test-results/completed-desktop.png'), fullPage: true });
  await target.click();
  assert.equal(await page.locator('.lock-task.is-done').count(), 0);
  await list.focus();
  await page.keyboard.press('Home');
  await page.keyboard.press('ArrowDown');
  await page.waitForTimeout(150);
  assert(await list.evaluate(el => el.scrollTop) > 0, 'Keyboard can scroll the box');
  await page.locator('.task-row[data-task-id=seed-1] [data-action=complete]').click();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('.lock-task[data-id=seed-1].is-done').count(), 1, 'Desktop completion synchronizes card');
  assert.equal(await page.locator('.lock-task').last().getAttribute('data-id'), 'seed-1', 'Completed pinned item goes below every pending item');
  await page.locator('.task-row[data-task-id=seed-3] [data-action=complete]').click();
  await page.waitForTimeout(1100);
  assert.deepEqual(await page.locator('.lock-task.is-done').evaluateAll(els => els.map(el => el.dataset.id)), ['seed-1', 'seed-3'], 'Latest completion appends after earlier completed tasks');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('.lock-task[data-id=seed-1].is-done').count(), 1, 'Completed state persists on refresh');
  assert.deepEqual(await page.locator('.lock-task.is-done').evaluateAll(els => els.map(el => el.dataset.id)), ['seed-1', 'seed-3'], 'Completion order persists on refresh');
  await page.locator('.lock-task[data-id=seed-1]').click();
  assert.equal(await page.locator('.lock-task').first().getAttribute('data-id'), 'seed-1', 'Restored pinned item returns to the pending section');
  await page.locator('.lock-task[data-id=seed-1]').click();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('.lock-task').last().getAttribute('data-id'), 'seed-1', 'Recompleted task is appended to the end again');
  assert.equal(await page.locator('.lock-task[data-id=seed-1]').evaluate(el => Number(getComputedStyle(el).opacity)), .5);
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const mp = await mobile.newPage();
  mp.on('pageerror', e => errors.push(e.message));
  await mp.goto(url, { waitUntil: 'networkidle' });
  const ml = mp.locator('#activity-list');
  const rect = await ml.boundingBox();
  const cdp = await mobile.newCDPSession(mp);
  const x = Math.round(rect.x + rect.width * .7), y = Math.round(rect.y + rect.height - 10);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  for (let i = 1; i <= 6; i++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - i * 11 }] });
    await mp.waitForTimeout(25);
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await mp.waitForTimeout(200);
  assert(await ml.evaluate(el => el.scrollTop) > 0, 'Touch swipe scrolls task box');
  assert.equal(await mp.evaluate(() => window.scrollY), 0, 'Swipe does not move outer page');
  await mp.locator('.lock-task[data-id=seed-5]').click();
  await mp.waitForTimeout(1150);
  await mp.screenshot({ path: path.resolve(__dirname, '../test-results/completed-mobile.png'), fullPage: true });
  await mp.emulateMedia({ reducedMotion: 'reduce' });
  await mp.locator('.lock-task[data-id=seed-6]').click();
  await mp.waitForTimeout(50);
  assert.equal(await mp.locator('.shard').count(), 0);
  assert.equal(await mp.locator('.lock-task[data-id=seed-6].is-done').count(), 1);
  assert.equal(await mp.locator('.completion-arrival').count(), 0);
  assert.equal(errors.length, 0, errors.join('\n'));
  await context.close(); await mobile.close();
  console.log('PASS: completed-last ordering, pinned-item completion, chronological completion persistence, restore/recomplete, wheel/touch/keyboard scrolling, fixed heading/footer, scroll preservation, strike/opacity, reduced motion.');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { await browser?.close(); });

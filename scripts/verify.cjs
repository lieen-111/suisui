const { chromium, review, url, launchOptions } = require('./test-environment.cjs');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
fs.mkdirSync(review, { recursive: true });
const errors = [];
let browser;
(async () => {
  browser = await chromium.launch(launchOptions);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(url, { waitUntil: 'networkidle' });
  await page.screenshot({ path: path.join(review, 'desktop.png'), fullPage: true });
  assert.equal(await page.locator('.task-row').count(), 6);
  assert.equal(await page.locator('.lock-task').count(), 6);
  assert(await page.locator('#wallpaper').evaluate(img => img.complete && img.naturalWidth > 0));
  await page.locator('.lock-task').first().click();
  await page.waitForTimeout(150);
  assert(await page.locator('.shard').count() >= 30, 'Task must visibly fragment');
  await page.screenshot({ path: path.join(review, 'fragmentation.png') });
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('.task-row').count(), 5);
  assert.equal(await page.locator('.lock-task').count(), 6);
  assert.equal(await page.locator('.lock-task.is-done').count(), 1);
  assert.equal(await page.locator('#done-count').textContent(), '1');
  await page.locator('#undo-button').click();
  assert.equal(await page.locator('.task-row').count(), 6);
  await page.locator('#task-input').fill('测试待办 <script> & 超长标题'.repeat(4));
  await page.locator('#task-group').selectOption('life');
  await page.locator('#add-form button[type=submit]').click();
  assert.equal(await page.locator('.task-row').count(), 7);
  await page.locator('.task-row').last().getByRole('button', { name: /^编辑/ }).click();
  await page.locator('#edit-title').fill('修改后的事项');
  await page.locator('.edit-form button.primary-button').click();
  assert.equal(await page.locator('.task-title').last().textContent(), '修改后的事项');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('.task-row').count(), 7);
  await page.locator('[data-filter=life]').click();
  assert.equal(await page.locator('.task-row').count(), 4);
  await page.locator('[data-filter=all]').click();
  await page.locator('[data-view=settings]').click();
  await page.locator('[data-density=compact]').click();
  assert.equal(await page.locator('.lock-task').count(), 7);
  assert.equal(await page.locator('#activity-list').evaluate(el => el.clientHeight), 96);
  await page.locator('[name=accent][value=rose]').check();
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()), '#b14c6b');
  await page.locator('[data-material=glass]').click();
  await page.locator('[data-card-color="#f5f7f3"]').click();
  await page.locator('#card-transparency').evaluate(el => { el.value = '46'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  assert.equal(await page.locator('#activity').evaluate(el => el.style.getPropertyValue('--card-blur')), '7px');
  assert.equal(await page.locator('#activity').evaluate(el => el.style.getPropertyValue('--card-ink')), '#182b22');
  assert.equal(await page.locator('#card-transparency-value').textContent(), '46%');
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('[data-view=settings]').click();
  assert.equal(await page.locator('#card-transparency').inputValue(), '46');
  assert.equal(await page.locator('#card-color').inputValue(), '#f5f7f3');
  assert.equal(await page.locator('[data-material=glass]').getAttribute('aria-pressed'), 'true');
  await page.locator('#card-color').evaluate(el => { el.value = '#999999'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.locator('#card-transparency').evaluate(el => { el.value = '0'; el.dispatchEvent(new Event('input', { bubbles: true })); });
  assert.equal(await page.locator('#activity').evaluate(el => el.style.getPropertyValue('--card-ink')), '#182b22', 'Automatic ink favors stronger contrast on mid-gray');
  await page.locator('#card-text').selectOption('light');
  assert.equal(await page.locator('#activity').evaluate(el => el.style.getPropertyValue('--card-ink')), '#f4fbf7');
  await page.locator('#reset-settings').click();
  await page.locator('[data-view=tasks]').click();
  await page.locator('#reset-button').click();
  await page.locator('[data-view=settings]').click();
  await page.locator('#reset-settings').click();
  await page.locator('[data-view=preview]').click();
  if (await page.locator('#close-toast').isVisible()) await page.locator('#close-toast').click();
  const phones = [[390, 844], [320, 568], [430, 932]];
  for (const [width, height] of phones) {
    await page.setViewportSize({ width, height });
    await page.screenshot({ path: path.join(review, `mobile-${width}.png`), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `No overflow at ${width}`);
    await page.locator('.nav-button[data-view=tasks]').click();
    await page.screenshot({ path: path.join(review, `tasks-${width}.png`), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `Task list fits ${width}`);
    await page.locator('.nav-button[data-view=preview]').click();
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('.lock-task').first().click();
  await page.waitForTimeout(50);
  assert.equal(await page.locator('.shard').count(), 0, 'Reduced motion disables fragments');
  await page.locator('#undo-button').click();
  if (await page.locator('#close-toast').isVisible()) await page.locator('#close-toast').click();
  await page.locator('#header-about').click();
  assert.equal(await page.locator('#about-dialog').evaluate(el => el.open), true);
  await page.locator('#close-about').click();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('.nav-button[data-view=tasks]').click();
  await page.locator('.task-row').first().getByRole('button', { name: /^完成/ }).click();
  await page.waitForTimeout(650);
  await page.locator('#completed-section').evaluate(el => { el.open = true; });
  await page.locator('.done-row [data-action=restore]').first().click();
  assert.equal(await page.locator('.task-row').count(), 6, 'Restore completed task');
  await page.locator('#completed-section').evaluate(el => { el.open = false; });
  await page.locator('.task-row').last().getByRole('button', { name: /^编辑/ }).click();
  await page.locator('.edit-form [data-action=delete]').click();
  assert.equal(await page.locator('.task-row').count(), 5);
  await page.locator('#undo-button').click();
  assert.equal(await page.locator('.task-row').count(), 6);
  await page.locator('.nav-button[data-view=settings]').click();
  await page.locator('#wallpaper-file').setInputFiles(path.resolve(__dirname, '../app/assets/lake.jpg'));
  await page.waitForTimeout(100);
  assert(await page.locator('#wallpaper').evaluate(img => img.src.startsWith('data:image/')), 'Local wallpaper upload');
  await page.locator('#reset-settings').click();
  await page.locator('#motion-toggle').uncheck();
  await page.locator('.nav-button[data-view=preview]').click();
  for (let i = 0; i < 6; i++) await page.locator('.lock-task[data-action=complete]').first().click();
  assert.equal(await page.locator('.lock-task.is-done').count(), 6);
  assert.equal(await page.locator('#remaining-label').textContent(), '全部完成 · 6 项');
  assert.equal(await page.locator('#done-count').textContent(), '6');
  await page.locator('.nav-button[data-view=tasks]').click();
  await page.locator('#reset-button').click();
  const downloadWait = page.waitForEvent('download');
  await page.locator('#export-button').click();
  const download = await downloadWait;
  const downloadPath = await download.path();
  const exported = JSON.parse(fs.readFileSync(downloadPath, 'utf8'));
  assert.equal(exported.tasks.length, 6, 'Export contains all tasks');
  assert.equal(exported.version, 2);
  assert.equal(exported.app, 'suisui');
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('PASS: fragmentation, retained completed tasks, undo, add/edit/delete/restore, persistence, grouping, density, accent, card appearance, upload, JSON export, all-complete state, reduced motion, disclosure, 320/390/430 layouts; no console errors.');
  await context.close();
  await browser.close();
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
